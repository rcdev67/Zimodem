def parse():
    lines = GLYPHS.split('\n')[1:]
    glyphs = {}
    i = 0
    while i < len(lines) and lines[i] != '':
        ch = ' ' if lines[i] == 'SPACE' else lines[i]   # a lone space would not survive editors
        assert len(ch) == 1, (i, ch)
        rows = lines[i + 1:i + 8]
        assert len(rows) == 7 and all(len(r) == 5 and set(r) <= set('.#') for r in rows), (ch, rows)
        glyphs[ch] = rows
        i += 8
    return glyphs


def main():
    glyphs = parse()
    want = [chr(c) for c in range(32, 127)]
    missing = [c for c in want if c not in glyphs]
    assert not missing, missing
    out = ['// The 5x7 font of the status display, ASCII 32 to 126: five column',
           '// bytes per glyph, bit 0 the top row. Written by',
           '// tools/font5x7/make_font.py from the glyphs drawn there; change them',
           '// there, not here.',
           '#ifndef ZDISPLAY_FONT_H',
           '#define ZDISPLAY_FONT_H',
           '',
           'static const uint8_t displayFont[95][5] = {']
    for c in want:
        rows = glyphs[c]
        cols = []
        for x in range(5):
            b = 0
            for y in range(7):
                if rows[y][x] == '#':
                    b |= 1 << y
            cols.append('0x%02x' % b)
        name = {'\\': 'backslash', "'": 'quote'}.get(c, c)
        out.append('  { %s },  // %s' % (', '.join(cols), name))
    out += ['};', '', '#endif', '']
    here = os.path.dirname(os.path.abspath(__file__))
    dst = os.path.join(here, '..', '..', 'zimodem', 'zdisplay_font.h')
    with open(dst, 'w', encoding='ascii', newline='\r\n') as f:   # like the rest of zimodem/
        f.write('\n'.join(out))
    print('wrote', os.path.normpath(dst), len(want), 'glyphs')


if __name__ == '__main__':
    main()
